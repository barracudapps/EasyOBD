// Single entry point to the Rust core.
// - Native app (Tauri): `invoke('api', { cmd, args })` → real adapters (USB, Bluetooth, BLE, Wi-Fi) + simulator.
// - Browser: the same Rust code compiled to WebAssembly (simulator, knowledge base, audio, training…).

type WasmModule = {
  default: (input?: unknown) => Promise<unknown>;
  Api: new () => { call(cmd: string, args: string): string };
  analyze_audio(samples: Float32Array, req: string): string;
};

export const isNative = typeof window !== 'undefined' && '__TAURI_INTERNALS__' in window;

let wasmApi: { call(cmd: string, args: string): string } | null = null;
let wasmMod: WasmModule | null = null;

async function wasm() {
  if (!wasmApi) {
    // Generated by scripts/build-wasm.sh into ui/public/wasm (served as a static file).
    const url = new URL('wasm/obd_wasm.js', document.baseURI).href;
    wasmMod = (await import(/* @vite-ignore */ url)) as WasmModule;
    await wasmMod.default();
    wasmApi = new wasmMod.Api();
  }
  return { api: wasmApi, mod: wasmMod! };
}

export async function call<T = unknown>(cmd: string, args: Record<string, unknown> = {}): Promise<T> {
  if (isNative) {
    const { invoke } = await import('@tauri-apps/api/core');
    return invoke<T>('api', { cmd, args });
  }
  const { api } = await wasm();
  try {
    return JSON.parse(api.call(cmd, JSON.stringify(args))) as T;
  } catch (e) {
    throw typeof e === 'string' ? e : (e as Error).message ?? String(e);
  }
}

export async function analyzeAudio<T>(samples: Float32Array, request: Record<string, unknown>): Promise<T> {
  if (isNative) return call<T>('audio_analyze', { samples: Array.from(samples), request });
  const { mod } = await wasm();
  return JSON.parse(mod.analyze_audio(samples, JSON.stringify(request))) as T;
}

export async function openUrl(url: string) {
  if (isNative) {
    const { openUrl: open } = await import('@tauri-apps/plugin-opener');
    await open(url);
  } else {
    window.open(url, '_blank', 'noopener');
  }
}

export function errorText(e: unknown): string {
  if (typeof e === 'string') return e;
  if (e instanceof Error) return e.message;
  return JSON.stringify(e);
}
